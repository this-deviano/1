/** R-8a. The numeric value is UNCHANGED from the briefed criterion (1e-4); only
    the measurement DOMAIN changed (silent regions only). A repair must not move
    the number it was judged by, or the repair is indistinguishable from
    threshold-shopping. */
const MAX_SILENT_DC = 1e-4;
/** R-8c. A full-scale source legitimately touches 1.0; the briefed `clipped === 0`
    was unsatisfiable on one by construction (FND-04). */
