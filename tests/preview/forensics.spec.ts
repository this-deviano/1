/** R-9. Normalized delivery must land on the requested sample peak ±0.1 dB. */
const NORMALIZE_TOLERANCE_DB = 0.1;
/** Exactly-scripted key spacing, in ms, for the deterministic input path (R-8c). */
const MIDI_KEY_SPACING_MS = 70;
/** One model step — the tolerance for the deterministic input path's tick
    derivation (240 ticks ≈ 127 ms at 118 qpm). */
